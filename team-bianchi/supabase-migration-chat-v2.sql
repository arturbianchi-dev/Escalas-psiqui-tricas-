-- Team Bianchi additive migration: do not drop existing tables or messages.
-- Run in Supabase SQL Editor after reviewing the comments.
alter table public.profiles add column if not exists email text;

update public.profiles p
set email = u.email
from auth.users u
where u.id = p.id and (p.email is null or p.email = '');

create or replace function public.handle_new_team_bianchi_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), 'user', new.email)
  on conflict (id) do update set
    full_name = coalesce(nullif(excluded.full_name,''), public.profiles.full_name),
    email = excluded.email;
  return new;
end;
$$;

-- Existing trigger is retained/replaced in place.
drop trigger if exists on_auth_user_created_team_bianchi on auth.users;
create trigger on_auth_user_created_team_bianchi
after insert on auth.users
for each row execute function public.handle_new_team_bianchi_user();

-- Collective chat. Individual messages remain in public.chat_messages.
create table if not exists public.team_group_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create index if not exists team_group_messages_created_idx
  on public.team_group_messages (created_at desc);
alter table public.team_group_messages enable row level security;

drop policy if exists "group messages read authenticated" on public.team_group_messages;
create policy "group messages read authenticated"
on public.team_group_messages for select to authenticated
using (true);

drop policy if exists "group messages insert self" on public.team_group_messages;
create policy "group messages insert self"
on public.team_group_messages for insert to authenticated
with check (sender_id = auth.uid());

grant select, insert on public.team_group_messages to authenticated;
grant usage, select on sequence public.team_group_messages_id_seq to authenticated;

-- Email is visible only to admins; users can still read their own profile.
drop policy if exists "profile read own or admin" on public.profiles;
create policy "profile read own or admin" on public.profiles for select to authenticated
using (id = auth.uid() or public.is_team_admin());

-- Admins can update profiles, including granting admin to another trusted account.
-- This policy is scoped to admins and does not grant normal users role-edit rights.
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for update to authenticated
using (public.is_team_admin())
with check (public.is_team_admin());

-- Ensure regular users cannot promote themselves via direct profile updates.
drop policy if exists "profile update own name only" on public.profiles;
create policy "profile update own name only" on public.profiles for update to authenticated
using (id = auth.uid() and role = 'user')
with check (id = auth.uid() and role = 'user');

grant select, update on public.profiles to authenticated;
